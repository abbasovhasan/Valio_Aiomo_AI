 checks.push('Role denial requests a fresh server identity instead of granting frontend authority');
 let config=client.api('/auth/demo');const configCall=calls.at(-1),configTransport=transport.shift();client.retireSessionRequests();
 assert(!configCall.options.signal.aborted,'Public role discovery was unnecessarily cancelled');configTransport.resolve(response(200,{enabled:true}));assert((await config).enabled===true,'Public role discovery lost during restore');
