 checks.push('The current session receives its own authenticated response');
 let expired=client.api('/preferences').catch(e=>e);transport.shift().resolve(response(401,{detail:{message:'Sign in'}}));await expired;
 assert(events.length===1&&events[0]==='aimo-session-expired','Current expiry did not reach the UI');
